def test_rollback_restores_known_phase_backup(tmp_path):
    db = _write_db(tmp_path / "data.db")
    root = _write_project(tmp_path / "repo", db)
    xml = _write_xml(tmp_path / "InstrumentInfo_USDJPY_Darwinex.xml")
    backup = backup_payload(root, db_path=db, process_checker=lambda: [])
    plan = build_plan(root, xml_path=xml, db_path=db, target_instrument="USDJPY_darwinex", backup_id=backup["backupId"])

    applied = apply_payload(
        root,
        xml_path=xml,
        db_path=db,
        target_instrument="USDJPY_darwinex",
        backup_id=backup["backupId"],
        approval=plan["approvalTemplate"],
        apply=True,
        process_checker=lambda: [],
    )
    assert applied["ok"] is True

    rollback = rollback_payload(root, backup_id=backup["backupId"], db_path=db, process_checker=lambda: [])

    assert rollback["status"] == "rollback_restored_known_phase_backup"
    assert _row(db)["POINTVALUE"] == 627.0
